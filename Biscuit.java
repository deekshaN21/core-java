class Biscuit {
    static String brandName = "Parle";
    static String productName = "Parle-G";
    static String biscuitType = "Glucose";
    static int weightGrams = 250;
    static String flavor = "Original";
    static int calories = 450;
    static boolean sugarFree = false;
    static double price = 30.00;
    static String expiryDate = "06-2026";
    static String manufactureCountry = "India";

    public static void main(String[] args) {
        System.out.println("Brand Name : " + brandName);
        System.out.println("Product Name : " + productName);
        System.out.println("Biscuit Type : " + biscuitType);
        System.out.println("Weight (grams) : " + weightGrams);
        System.out.println("Flavor : " + flavor);
        System.out.println("Calories : " + calories);
        System.out.println("Sugar Free : " + sugarFree);
        System.out.println("Price : " + price);
        System.out.println("Expiry Date : " + expiryDate);
        System.out.println("Manufactured In : " + manufactureCountry);
    }
}
